// Generates the width tables of zcode-proxy-src/src/tui/width-core.mjs from
// the Unicode Character Database.
//
// usage: node scripts/gen-width-tables.mjs <ucd-dir> [--check]
//
// <ucd-dir> holds four files of one UCD version, downloaded from
// https://www.unicode.org/Public/<version>/ucd/:
//   EastAsianWidth.txt                    (W/F → 2 cells)
//   extracted/DerivedGeneralCategory.txt  (Mn/Me/Cf → 0 cells)
//   emoji/emoji-variation-sequences.txt   (bases for which VS16 → 2 cells)
//   auxiliary/GraphemeBreakProperty.txt   (code points that can join a cluster)
// The files may sit flat in <ucd-dir> or in those subdirectories.
//
// The script rewrites only the block between the GENERATED markers in
// width-core.mjs. With --check it rewrites nothing and exits 1 when the
// committed block differs from what the input files produce.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = join(ROOT, "zcode-proxy-src", "src", "tui", "width-core.mjs");
const BEGIN = "// BEGIN GENERATED by scripts/gen-width-tables.mjs — do not edit by hand";
const END = "// END GENERATED";

const args = process.argv.slice(2);
const dir = args.find((a) => !a.startsWith("--"));
const check = args.includes("--check");
if (!dir) {
  console.error("usage: node scripts/gen-width-tables.mjs <ucd-dir> [--check]");
  process.exit(2);
}

function read(name, sub) {
  const flat = join(dir, name);
  const nested = join(dir, sub, name);
  const path = existsSync(flat) ? flat : nested;
  const bytes = readFileSync(path);
  return { text: bytes.toString("utf8"), sha256: createHash("sha256").update(bytes).digest("hex") };
}

/** Parse `XXXX(..YYYY)? ; value` lines into [lo, hi, value] triples. */
function parseRanges(text) {
  const out = [];
  for (const raw of text.split("\n")) {
    const line = raw.replace(/#.*/, "").trim();
    if (!line) continue;
    const [cps, value] = line.split(";").map((s) => s.trim());
    const [a, b] = cps.split("..");
    out.push([parseInt(a, 16), parseInt(b ?? a, 16), value]);
  }
  return out;
}

function merge(ranges) {
  const sorted = [...ranges].sort((x, y) => x[0] - y[0]);
  const out = [];
  for (const [lo, hi] of sorted) {
    const last = out[out.length - 1];
    if (last && lo <= last[1] + 1) last[1] = Math.max(last[1], hi);
    else out.push([lo, hi]);
  }
  return out;
}

function subtract(ranges, cp) {
  const out = [];
  for (const [lo, hi] of ranges) {
    if (cp < lo || cp > hi) out.push([lo, hi]);
    else {
      if (lo < cp) out.push([lo, cp - 1]);
      if (cp < hi) out.push([cp + 1, hi]);
    }
  }
  return out;
}

function version(text, re) {
  const m = text.match(re);
  if (!m) throw new Error(`cannot find the UCD version in a header (${re})`);
  return m[1];
}

const eaw = read("EastAsianWidth.txt", ".");
const gc = read("DerivedGeneralCategory.txt", "extracted");
const evs = read("emoji-variation-sequences.txt", "emoji");
const gcb = read("GraphemeBreakProperty.txt", "auxiliary");

const ucdVersion = version(eaw.text, /^# EastAsianWidth-(\d+\.\d+\.\d+)\.txt/m);
const gcVersion = version(gc.text, /^# DerivedGeneralCategory-(\d+\.\d+\.\d+)\.txt/m);
const evsVersion = version(evs.text, /^# Version: (\d+\.\d+)/m);
const gcbVersion = version(gcb.text, /^# GraphemeBreakProperty-(\d+\.\d+\.\d+)\.txt/m);
if (gcVersion !== ucdVersion || gcbVersion !== ucdVersion || !ucdVersion.startsWith(`${evsVersion}.`)) {
  throw new Error(`UCD files disagree: EastAsianWidth ${ucdVersion}, DerivedGeneralCategory ${gcVersion}, GraphemeBreakProperty ${gcbVersion}, emoji-variation-sequences ${evsVersion}`);
}

// 2 cells: East_Asian_Width W or F.
const wide = merge(parseRanges(eaw.text).filter(([, , v]) => v === "W" || v === "F"));

// 0 cells: nonspacing and enclosing marks and format characters, except
// U+00AD SOFT HYPHEN (terminals draw it; wcwidth gives it 1), plus the Hangul
// medial vowels and final consonants (U+1160–11FF, U+D7B0–D7FF), which only
// ever extend a leading consonant's syllable block.
let zero = merge([
  ...parseRanges(gc.text).filter(([, , v]) => v === "Mn" || v === "Me" || v === "Cf"),
  [0x1160, 0x11ff], [0xd7b0, 0xd7ff],
]);
zero = subtract(zero, 0x00ad);

// Bases for which `<base> U+FE0F` is a valid emoji-style variation sequence.
const vs16 = merge(
  evs.text.split("\n")
    .map((l) => l.replace(/#.*/, "").trim())
    .filter((l) => /\bFE0F\s*;\s*emoji style/i.test(l))
    .map((l) => { const cp = parseInt(l.split(/\s+/)[0], 16); return [cp, cp]; }),
);

// Code points that can be part of a multi-code-point cluster other than as its
// first, standalone-able base (UAX #29 GB6–GB13): Extend, ZWJ, SpacingMark,
// Prepend, Hangul L/V/T and regional indicators. LV/LVT syllables are left
// out: they only join a FOLLOWING V/T, which is itself in this set. A string
// without any of these code points segments into single code points.
const joiners = merge(parseRanges(gcb.text).filter(([, , v]) =>
  ["Extend", "ZWJ", "SpacingMark", "Prepend", "L", "V", "T", "Regional_Indicator"].includes(v)));

const hex = (n) => `0x${n.toString(16)}`;
const table = (name, ranges, doc) => {
  const flat = ranges.flatMap(([a, b]) => [hex(a), hex(b)]);
  const lines = [];
  for (let i = 0; i < flat.length; i += 12) lines.push(`  ${flat.slice(i, i + 12).join(", ")},`);
  return `/** ${doc} (${ranges.length} ranges, flat [lo, hi, lo, hi, …]). */\nconst ${name} = [\n${lines.join("\n")}\n];`;
};

const block = [
  BEGIN,
  `// Source: Unicode ${ucdVersion} (https://www.unicode.org/Public/${ucdVersion}/ucd/)`,
  `//   EastAsianWidth.txt                    sha256 ${eaw.sha256}`,
  `//   extracted/DerivedGeneralCategory.txt  sha256 ${gc.sha256}`,
  `//   emoji/emoji-variation-sequences.txt   sha256 ${evs.sha256}`,
  `//   auxiliary/GraphemeBreakProperty.txt   sha256 ${gcb.sha256}`,
  `export const UNICODE_VERSION = "${ucdVersion}";`,
  table("WIDE", wide, "East_Asian_Width W or F: two cells"),
  table("ZERO", zero, "Mn, Me, Cf (minus U+00AD) and Hangul medial/final jamo: zero cells"),
  table("VS16_BASES", vs16, "Bases of emoji-style variation sequences: base + U+FE0F is two cells"),
  table("JOINERS", joiners, "Grapheme_Cluster_Break Extend/ZWJ/SpacingMark/Prepend/L/V/T/Regional_Indicator: may join a cluster"),
  END,
].join("\n");

const current = readFileSync(TARGET, "utf8");
const start = current.indexOf(BEGIN);
const stop = current.indexOf(END);
if (start < 0 || stop < start) throw new Error(`${TARGET} has no GENERATED block`);
const next = current.slice(0, start) + block + current.slice(stop + END.length);

if (check) {
  if (next !== current) {
    console.error("width-core.mjs tables differ from the UCD input; re-run without --check");
    process.exit(1);
  }
  console.log(`width-core.mjs tables match Unicode ${ucdVersion}`);
} else {
  writeFileSync(TARGET, next);
  console.log(`width-core.mjs: Unicode ${ucdVersion}, ${wide.length} wide, ${zero.length} zero, ${vs16.length} VS16 base, ${joiners.length} joiner ranges`);
}
