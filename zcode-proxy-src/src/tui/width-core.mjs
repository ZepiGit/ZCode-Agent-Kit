/**
 * Shared width core: display width in terminal cells, for the proxy TUI (Bun,
 * through width.ts) and the kit CLI (Node, through lib/term/width.mjs).
 * Plain ESM, no imports, no runtime-specific APIs; types in
 * width-core.d.mts.
 *
 * Width is measured per grapheme cluster (Intl.Segmenter), as grapheme-aware
 * terminals (mode 2027, Windows Terminal ≥ 1.22) advance the cursor:
 *   - 0 when every code point of the cluster is zero-width or a control;
 *   - 2 when any code point is East_Asian_Width W/F (UCD table below);
 *   - 2 when U+FE0F (VS16) follows a valid emoji-variation base;
 *   - 2 for a regional-indicator pair (a flag);
 *   - otherwise 1, and never more than 2.
 * Ambiguous (EAW=A) characters are narrow, the UAX #11 default. TAB and the
 * other C0/C1 controls count 0 cells, as before.
 *
 * Fast paths keep the TUI's frame time: printable ASCII is measured by length,
 * and text without combining or joining code points (UCD GraphemeBreakProperty
 * Extend/ZWJ/SpacingMark/Prepend/L/V/T/RI: the JOINERS table) is summed code
 * point by code point, because every code point is its own cluster. Only the
 * rest of a string from its first joiner is segmented. Width errors on exotic
 * content are cosmetic only (a mis-padded log line), never fatal.
 */

