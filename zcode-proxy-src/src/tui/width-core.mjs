function inRanges(cp, ranges) {
  let lo = 0;
  let hi = (ranges.length >> 1) - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (cp < ranges[mid * 2]) hi = mid - 1;
    else if (cp > ranges[mid * 2 + 1]) lo = mid + 1;
    else return true;
  }
  return false;
}

/** Width of one code point on its own (0, 1 or 2). */
function codePointWidth(cp) {
  if (cp < 0x7f) return cp >= 0x20 ? 1 : 0;
  if (cp < 0xa0) return 0;
  if (cp < 0x300) return 1;
  if (inRanges(cp, ZERO)) return 0;
  if (inRanges(cp, WIDE)) return 2;
  return 1;
}

/** Width of one grapheme cluster (0, 1 or 2). */
function clusterWidth(cluster) {
  if (cluster.length === 1) return codePointWidth(cluster.charCodeAt(0));
  let w = 0;
  let prev = -1;
  let regional = 0;
  for (let i = 0; i < cluster.length; ) {
    const cp = cluster.codePointAt(i);
    i += cp > 0xffff ? 2 : 1;
    if (cp === 0xfe0f) {
      if (prev >= 0 && inRanges(prev, VS16_BASES)) return 2;
    } else if (cp >= 0x1f1e6 && cp <= 0x1f1ff && ++regional === 2) {
      return 2;
    } else {
      const cw = codePointWidth(cp);
      if (cw === 2) return 2;
      if (cw > w) w = cw;
    }
    prev = cp;
  }
  return w;
}

let segmenter = null;
/** Grapheme segmenter, created on first use (text with a joiner). */
function graphemes(s) {
  segmenter ??= new Intl.Segmenter(undefined, { granularity: "grapheme" });
  return segmenter.segment(s);
}

/** True when the code point can join a cluster (never true below U+0300). */
function joins(cp) {
  return cp >= 0x300 && inRanges(cp, JOINERS);
}

/** Remove ANSI escape sequences so the result can be measured / compared. */
export function stripAnsi(s) {
  return s.indexOf("\x1b") === -1 ? s : s.replace(ANSI_RE, "");
}

/** Display width in terminal cells (ANSI escape sequences count as 0). */
export function displayWidth(s) {
  const plain = stripAnsi(s);
  if (PRINTABLE_ASCII.test(plain)) return plain.length;
  let w = 0;
  let prev = 0; // start of the previous code point: the base a joiner may extend
  let prevW = 0;
  for (let i = 0; i < plain.length; ) {
    const cp = plain.codePointAt(i);
    if (joins(cp)) {
      w -= prevW;
      for (const { segment } of graphemes(plain.slice(i === 0 ? 0 : prev))) w += clusterWidth(segment);
      return w;
    }
    prevW = codePointWidth(cp);
    w += prevW;
    prev = i;
    i += cp > 0xffff ? 2 : 1;
  }
  return w;
}

/**
 * Truncate to `max` display cells, appending `…` when anything was cut. Cuts
 * fall on grapheme-cluster boundaries only. ANSI sequences are stripped first;
 * callers that want colour re-wrap the result themselves.
 */
export function truncateToWidth(s, max, ellipsis = "…") {
  if (max <= 0) return "";
  const plain = stripAnsi(s);
  const budget = max - displayWidth(ellipsis);
  if (PRINTABLE_ASCII.test(plain)) {
    return plain.length <= max ? plain : plain.slice(0, Math.max(0, budget)) + ellipsis;
  }
  // `cut` is where the kept text ends: the first cluster that would not fit
  // the budget (before the ellipsis) freezes it. The text is returned whole
  // if its total width never passes `max`.
  let w = 0;
  let cut = -1;
  let prev = 0;
  let prevW = 0;
  let i = 0;
  while (i < plain.length) {
    const cp = plain.codePointAt(i);
    if (joins(cp)) break;
    const cw = codePointWidth(cp);
    if (cut < 0 && w + cw > budget) cut = i;
    w += cw;
    if (w > max) return plain.slice(0, cut) + ellipsis;
    prev = i;
    prevW = cw;
    i += cp > 0xffff ? 2 : 1;
  }
  if (i >= plain.length) return plain;
  // Segment the rest, starting again at the previous code point: it may be
  // the base of the cluster the joiner belongs to.
  const from = i === 0 ? 0 : prev;
  if (from < i) {
    w -= prevW;
    if (cut === from) cut = -1;
  }
  for (const { segment, index } of graphemes(plain.slice(from))) {
    const cw = clusterWidth(segment);
    if (cut < 0 && w + cw > budget) cut = from + index;
    w += cw;
    if (w > max) return plain.slice(0, cut) + ellipsis;
  }
  return plain;
}

/** Pad with spaces (display-width aware) so the string occupies exactly `width` cells. */
export function padEndWidth(s, width) {
  const pad = width - displayWidth(s);
  return pad > 0 ? s + " ".repeat(pad) : s;
}
