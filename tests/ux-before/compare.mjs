// Byte comparison of two UX capture sets (tests/ux-before/capture/capture.mjs
// output): the committed BEFORE baseline and a fresh capture of the current
// tree. Used by tests/ux-before-equivalence.test.mjs, the proof of "no visible
// change" for tickets 06–08.
//
// The baseline files stay verbatim (640 captures at 0960696). Values that
// change from run to run, whatever the code, are normalised on BOTH sides by
// the explicit list below; nothing else is. The list never touches status
// words, exit codes or the check grammar (spec, Testing Decisions).
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

/** [name, pattern, replacement]: run-to-run values only. */
export const VOLATILE = Object.freeze([
  // Relative ages computed from the wall clock against the fixture's fixed timestamps.
  ["relative age", /\b\d+[smhd] ago\b/g, "<AGE> ago"],
  // JWT issue time the fixture proxy derives from Date.now().
  ["epoch issuedAt", /("issuedAt": )\d+/g, "$1<EPOCH>"],
  // Commit ids of the fixture git origin (commit timestamps differ per run).
  ["git commit range", /\b[0-9a-f]{7}\.\.[0-9a-f]{7}\b/g, "<SHA>..<SHA>"],
  // git's own transfer-progress meter during `update` of a checkout install:
  // its wording, counts, rate and ESC[K placement differ by git version
  // (2.43: "…pack-reused 0\x1b[K"; 2.56: "\x1b[K…pack-reused 0 (from 0)").
  // A run of these lines becomes one marker line. Only git prints them: every
  // line starts with "remote: " or "Receiving|Unpacking|Resolving objects|deltas: ".
  ["git transfer progress", /^(?:(?:\x1b\[K)?(?:remote: |(?:Receiving|Unpacking|Resolving) (?:objects|deltas): )[^\n]*\n)+/gm, "<GIT TRANSFER PROGRESS>\n"],
  // git's diffstat of the fixture's own "upstream" commit during `update` of a
  // checkout install (`git merge --ff-only` output). The fixture rewrites
  // package.json with JSON.stringify, so the counts depend on the checkout:
  // 2 on an LF checkout, every line (68, 70, …) on a CRLF one (windows CI).
  // Only git's exact shape matches: one leading space, a path, ` | `, a count
  // and a +/- graph (coloured on a TTY) to the end of the line; the path stays.
  ["git diffstat", /^( [^\s|][^\n|]*? \| +)\d+ (?:\x1b\[[0-9;]*m|[+-])+$/gm, "$1<N> <GRAPH>"],
  ["git diffstat summary", /^ \d+ files? changed(?:, \d+ insertions?\(\+\))?(?:, \d+ deletions?\(-\))?$/gm, " <N> file(s) changed, <N> insertion(s)(+), <N> deletion(s)(-)"],
  // SHA-256 of a fixture archive built at capture time (tar mtimes differ per run).
  ["archive sha256", /(actual {3})[0-9a-f]{64}\b/g, "$1<SHA256>"],
  // A proxy key generated by a fresh fixture installation (never the synthetic fixture key).
  ["generated proxy key", /(API key \(Bearer \/ x-api-key\): {2})(?!UXFIXTURE-)[A-Za-z0-9_-]{43}\b/g, "$1<GENERATED_KEY>"],
  // Size of the fixture release tree, which grows with every kit file added under cli/ or lib/.
  ["fixture release size", /\(\d+ files updated, \d+ removed\)/g, "(<N> files updated, <N> removed)"],
]);

export const normaliseVolatile = (text) => VOLATILE.reduce((s, [, re, to]) => s.replace(re, to), text);

/** Captures that are not command output: the static install.ps1 source excerpt (pwsh cannot run on Linux). */
export const NOT_OUTPUT = Object.freeze([/^install\/install-ps1-static\//]);

function listFiles(root) {
  const files = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) walk(full);
      else files.push(relative(root, full).split(sep).join("/"));
    }
  };
  walk(root);
  return files.filter((f) => f !== "INDEX.md" && f !== "manifest.json" && !NOT_OUTPUT.some((re) => re.test(f))).sort();
}

const variantOf = (file) => file.split("/").pop().replace(/(\.stderr)?\.(txt|ansi)$/, "");
const keyOf = (m) => `${m.group}/${m.id}/${m.variant}`;

/**
 * Compare `fresh` against `baseline`, limited to `variants` (all when omitted)
 * and to captures whose `<group>/<scenario>` matches `only` (all when omitted).
 * Returns a list of human-readable differences; empty means equivalent.
 */
export function compareCaptures(baseline, fresh, { variants, only } = {}) {
  const inScope = (key) => !only || only.test(key);
  const keep = (file) => (!variants || variants.includes(variantOf(file))) && inScope(file.split("/").slice(0, 2).join("/"));
  const keepM = (m) => (!variants || variants.includes(m.variant)) && inScope(`${m.group}/${m.id}`);
  const diffs = [];
  const want = listFiles(baseline).filter(keep);
  const got = new Set(listFiles(fresh).filter(keep));
  for (const file of want) {
    if (!got.has(file)) { diffs.push(`missing: ${file}`); continue; }
    got.delete(file);
    const a = normaliseVolatile(readFileSync(join(baseline, file), "utf8"));
    const b = normaliseVolatile(readFileSync(join(fresh, file), "utf8"));
    if (a !== b) {
      const al = a.split("\n"), bl = b.split("\n");
      const at = al.findIndex((line, i) => line !== bl[i]);
      diffs.push(`differs: ${file} line ${at + 1}\n  before: ${JSON.stringify(al[at])}\n  now:    ${JSON.stringify(bl[at])}`);
    }
  }
  for (const file of got) diffs.push(`unexpected: ${file}`);
  // Exit codes are visible behaviour too; capture errors are failures, never skips.
  const manifest = (dir) => (existsSync(join(dir, "manifest.json")) ? JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8")) : []);
  const now = new Map(manifest(fresh).map((m) => [keyOf(m), m]));
  for (const m of manifest(fresh)) if (m.error && keepM(m)) diffs.push(`capture error: ${keyOf(m)}: ${m.error}`);
  // A baseline with failed captures proves nothing for those captures: fail loudly.
  for (const m of manifest(baseline)) if (m.error && keepM(m)) diffs.push(`baseline capture error: ${keyOf(m)}: ${m.error}`);
  for (const m of manifest(baseline)) {
    if (!keepM(m)) continue;
    if (m.group === "install" && m.id === "install-ps1-static") continue;
    const n = now.get(keyOf(m));
    if (!n) diffs.push(`not captured: ${keyOf(m)}`);
    else if (!n.error && !m.error && n.exit !== m.exit) diffs.push(`exit code: ${keyOf(m)} was ${m.exit}, now ${n.exit}`);
  }
  return diffs;
}
