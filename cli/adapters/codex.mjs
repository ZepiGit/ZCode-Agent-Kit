// Adapter: Codex CLI — isolated CODEX_HOME under generated/, launched via
// bin/zcode-codex.cmd|.sh. The user's real ~/.codex is never touched; skills,
// rules and MCP servers outside the isolated home are unaffected (difference
// documented in harnesses/README.md).
import { existsSync } from "node:fs";
import { join } from "node:path";
import { commitFile, ensureDir } from "../../lib/edit.mjs";
import { bridgeArgs } from "../../lib/mcp-bridge.mjs";

export default {
  id: "codex",
  label: "Codex CLI",
  protocol: "Responses API (wire_api = \"responses\") via local proxy",
  primarySource: "https://developers.openai.com/codex/config-reference (checked 2026-11-04; codex 0.166.0: wire_api=\"responses\" is the only supported value)",

  apply(ctx, tx, log) {
    const port = ctx.port();
    const home = join(ctx.generated, "codex-home");
    const { created } = ensureDir(ctx, home);
    if (created) log(`  created ${home}`);
    // The launcher hint (and the config comment) name the
    // launcher that works on the user's OS. ctx.platform is the kit context's
    // platform, so both branches are testable.
    const windows = (ctx.platform ?? process.platform) === "win32";
    const launcher = windows ? "bin\\zcode-codex.cmd" : "bin/zcode-codex.sh";
    // The bridge flags on the command line; an older config.toml
    // is rewritten to this form through the transaction.
    const mcpArgs = bridgeArgs(`${ctx.root.replace(/\\/g, "/")}/mcp/zcode-harness-mcp/dist/index.js`).map((a) => JSON.stringify(a)).join(", ");
    const toml = `# Generated by zcode-kit — isolated CODEX_HOME for the ZCode kit.
# Your normal ~/.codex is untouched; use ${launcher} to enter this setup.
model = "glm-5.3"
model_provider = "zcode"
${windows ? '\n# Native restricted-token sandbox; no admin setup or full-access bypass.\n[windows]\nsandbox = "unelevated"\n' : ''}
[model_providers.zcode]
name = "ZCode (local proxy)"
base_url = "http://127.0.0.1:${port}/v1"
env_key = "ZCODE_PROXY_KEY"
wire_api = "responses"

[mcp_servers.zcode-harness]
command = "node"
args = [${mcpArgs}]
`;
    const configPath = join(home, "config.toml");
    const { wrote } = commitFile(ctx, tx, configPath, toml);
    if (wrote) {
      log(`  wrote ${configPath} (model provider + zcode-harness MCP)`);
      log(`  use via: ${launcher}  (e.g. ${launcher} exec "task")`);
    }
    return { changed: wrote };
  },

  /** The isolated CODEX_HOME lives in this installation's state: kit-owned by construction. */
  owned(ctx) {
    return existsSync(join(ctx.generated, "codex-home", "config.toml"));
  },

  verify(ctx) {
    return [{ name: "codex adapter artifact", ok: existsSync(join(ctx.generated, "codex-home", "config.toml")), detail: "generated/codex-home/config.toml" }];
  },
};
